-- ============================================================================
-- 快速跳转
-- 按下快捷键后给屏幕上每个单词标一个字母，按字母直接跳过去
-- ============================================================================
return {
	"smoka7/hop.nvim",
	opts = {
		hint_position = 3, -- 提示字母出现在单词的第 3 个字符位置
	},
	keys = {
		{ "<leader>hp", "<Cmd>HopWord<CR>", desc = "定点跳转", silent = true },
	},
}
